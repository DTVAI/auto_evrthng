@pytest.mark.parametrize("tool_id", sorted(EXPECTED))
def test_independent_example_business_value(tool_id):
    module = domain_for(tool_id)
    result = module.run(tool_id, deepcopy(module.SAMPLES[tool_id]))
    path, expected = EXPECTED[tool_id]
    actual = result["data"]
    for key in path:
        actual = actual[key]
    assert type(actual) is type(expected) and actual == expected


def test_expected_values_cover_every_active_tool():
    from app.registry import catalog

    assert set(EXPECTED) == {item["id"] for item in catalog()}
